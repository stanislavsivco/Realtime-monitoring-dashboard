package com.realtime_monitoring_dashboard.backend.repository;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;

import java.util.List;

import javax.sql.DataSource;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

import com.realtime_monitoring_dashboard.backend.model.Device;
import com.realtime_monitoring_dashboard.backend.model.Role;
import com.realtime_monitoring_dashboard.backend.model.User;
import com.realtime_monitoring_dashboard.backend.support.PostgresTestDatabase;
import com.realtime_monitoring_dashboard.backend.support.SchemaInspector;

@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
class LegacySchemaMigrationIntegrationTest {

    private static final String[] LEGACY_SCHEMA = {
            "create table users ("
                    + "id bigint generated by default as identity primary key, "
                    + "username varchar(255) not null, "
                    + "password varchar(255) not null, "
                    + "role varchar(255) not null)",
            "insert into users (username, password, role) values "
                    + "('legacy-admin', 'x', 'ADMIN'), ('legacy-viewer', 'x', 'VIEWER')",
            "create table devices ("
                    + "id bigint generated by default as identity primary key, "
                    + "name varchar(255), "
                    + "type varchar(255), "
                    + "location varchar(255), "
                    + "status varchar(255))",
            "insert into devices (name, type, location, status) values "
                    + "('legacy-1', 'Server', 'DC1', 'ONLINE'), ('legacy-2', 'Router', 'DC2', 'OFFLINE')"
    };

    @DynamicPropertySource
    static void postgres(DynamicPropertyRegistry registry) {
        PostgresTestDatabase.registerWithSetup(registry, LEGACY_SCHEMA);
    }

    @Autowired
    private DataSource dataSource;
    @Autowired
    private UserRepository userRepository;
    @Autowired
    private DeviceRepository deviceRepository;

    private SchemaInspector schema;

    @BeforeEach
    void setUp() {
        schema = new SchemaInspector(dataSource);
    }

    @Test
    void existingUsersGetTokenVersionZero() {
        Integer users = schema.jdbc().queryForObject("select count(*) from users", Integer.class);
        Integer withZero = schema.jdbc().queryForObject(
                "select count(*) from users where token_version = 0", Integer.class);

        assertThat(users).isEqualTo(2);
        assertThat(withZero).isEqualTo(2);
    }

    @Test
    void existingDevicesBecomeSimulated() {
        Integer devices = schema.jdbc().queryForObject("select count(*) from devices", Integer.class);
        Integer simulated = schema.jdbc().queryForObject(
                "select count(*) from devices where simulated = true", Integer.class);

        assertThat(devices).isEqualTo(2);
        assertThat(simulated).isEqualTo(2);
    }

    @Test
    void addedColumnsAreNotNullableAndKeepTheirDefaults() {
        assertThat(schema.isNullable("users", "token_version")).isFalse();
        assertThat(schema.columnDefault("users", "token_version")).isEqualTo("0");
        assertThat(schema.isNullable("devices", "simulated")).isFalse();
        assertThat(schema.columnDefault("devices", "simulated")).isEqualTo("true");
    }

    @Test
    void entitiesLoadFromMigratedRows() {
        List<User> users = userRepository.findAll();
        List<Device> devices = deviceRepository.findAll();

        assertThat(users).hasSize(2).allSatisfy(user -> assertThat(user.getTokenVersion()).isZero());
        assertThat(devices).hasSize(2).allSatisfy(device -> assertThat(device.isSimulated()).isTrue());
    }

    @Test
    void ddlAutoDoesNotAddUniqueConstraintToExistingUsersTable() {
        assertThat(schema.uniqueConstraintCount("users", "username")).isZero();

        assertDoesNotThrow(() -> userRepository.saveAndFlush(
                User.builder().username("legacy-admin").password("y").role(Role.VIEWER).build()));
    }

    @Test
    void ddlAutoDoesNotAddUniqueConstraintToExistingDevicesTable() {
        assertThat(schema.uniqueConstraintCount("devices", "name")).isZero();
    }

    @Test
    void indexesAreCreatedNextToMigratedTables() {
        assertThat(schema.indexColumns("idx_metrics_device_timestamp")).containsExactly("device_id", "timestamp");
        assertThat(schema.indexColumns("idx_alerts_device_resolved")).containsExactly("device_id", "resolved");
    }
}